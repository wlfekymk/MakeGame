namespace MakeGame.Data
{
    /// <summary>
    /// B2-15: 플레이어가 설치(빌드)한 구조물의 종류. 세이브 파일에서 구조물 하나가 어떤 컴포넌트로
    /// 복원돼야 하는지 구분하는 용도로 쓰인다(Systems.SaveData.StructureSaveEntry.type 참고).
    /// </summary>
    /// <remarks>
    /// ⚠️ **값은 언제나 맨 끝에만 추가한다.** JsonUtility는 enum을 이름이 아니라 **정수**로 기록하므로
    /// (StructureSaveEntry.type), 중간에 하나만 끼워 넣어도 그 뒤의 모든 값이 한 칸씩 밀려
    /// 기존 세이브의 모닥불이 쉼터로, 쉼터가 증류기로 되살아난다. 순서 변경·삭제·개명도 같은 이유로 금지다.
    /// 아래 값에 명시적인 정수를 적어 두는 것은 그 규칙을 코드로 못박아 두기 위한 것이며,
    /// 앞의 세 값은 예전(암묵적 0/1/2)과 완전히 같은 숫자라 기존 세이브 파일의 해석이 1도 바뀌지 않는다.
    /// </remarks>
    public enum StructureType
    {
        Campfire = 0,   // 모닥불
        Shelter = 1,    // 쉼터
        WaterStill = 2, // 물 증류기

        // ── 제작 시설 3종 (제작대 배치) ─────────────────────────────────────────────
        // **맨 끝에 추가만 했다.** 위 세 값의 정수는 그대로다.
        // 종류마다 별도의 값을 주고 StructureSaveEntry에는 새 필드를 하나도 만들지 않는다 - 제작 시설은
        // 위치·회전 말고 저장할 상태가 없어서(연료도 내용물도 없다) type 하나로 복원에 필요한 정보가
        // 전부 갖춰진다. 기존 세 종류가 각자 전용 필드를 갖는 것과 대비되는, 가장 싼 확장이다.
        Workbench = 3,  // 제작대
        Furnace = 4,    // 용광로
        Loom = 5        // 베틀
    }
}
